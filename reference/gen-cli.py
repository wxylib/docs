#!/usr/bin/env python3
"""Write reference/cli.qmd from the `wxy` command's own help text.

    python3 reference/gen-cli.py path/to/wxy [core-commit]

Every command and subcommand is found by walking the "Commands:" section of
`--help`, so a new subcommand in wxylib/core appears here with no edit. The
publish workflow builds `wxy` from core's main and runs this before
rendering; the committed page is only what a local render shows.
"""

import pathlib
import re
import subprocess
import sys

OUT = pathlib.Path(__file__).with_name("cli.qmd")


def help_text(wxy, path):
    out = subprocess.run([wxy, *path, "--help"], check=True,
                         capture_output=True, text=True).stdout
    return out.rstrip() + "\n"


def subcommands(text):
    """Names under "Commands:", leaving out clap's own `help`."""
    names, inside = [], False
    for line in text.splitlines():
        if line.strip() == "Commands:":
            inside = True
        elif inside and not line.startswith("  "):
            inside = False
        elif inside:
            m = re.match(r"  (\S+)", line)
            if m and m.group(1) != "help":
                names.append(m.group(1))
    return names


def walk(wxy, path=()):
    text = help_text(wxy, path)
    yield path, text
    for name in subcommands(text):
        yield from walk(wxy, path + (name,))


def main():
    wxy = sys.argv[1]
    commit = sys.argv[2] if len(sys.argv) > 2 else None
    version = subprocess.run([wxy, "--version"], check=True,
                             capture_output=True, text=True).stdout.strip()
    source = "wxylib/core"
    if commit:
        source = (f"[wxylib/core@{commit[:7]}]"
                  f"(https://github.com/wxylib/core/tree/{commit})")
    pages = list(walk(wxy))
    lines = [
        "---",
        'title: "wxy command reference"',
        "---",
        "",
        "<!-- Generated by reference/gen-cli.py from `wxy --help`; do not",
        "     edit by hand. Change the doc comments in",
        "     crates/wxy-cli/src/main.rs in wxylib/core instead. -->",
        "",
        f"Generated from the help text of `{version}`, built from {source}.",
        "Each section is exactly what `wxy <command> --help` prints.",
        "Worked examples are in the",
        "[how-tos](../vignettes/README.md).",
        "",
    ]
    for path, text in pages:
        name = " ".join(("wxy",) + path)
        lines += [f"## `{name}`" + (" {#wxy-" + "-".join(path) + "}"
                                    if path else " {#wxy}"),
                  "", "```text", text.rstrip(), "```", ""]
    page = "\n".join(lines)
    page.encode("ascii")  # help text goes into the repo: ASCII only
    OUT.write_text(page)
    print(f"wrote {OUT} ({len(pages)} commands)")


if __name__ == "__main__":
    main()
